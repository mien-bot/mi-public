import { PDFDocument, StandardFonts, degrees, rgb } from "pdf-lib";

/**
 * The Mi mark, stamped onto every PDF Mi publishes.
 *
 * These are the same vector paths the application draws on screen and ships as the
 * packaged application icon (`components/MiMark.tsx`, `assets/mi-icon.png`). Keep the two
 * in sync: a PDF that carries a different glyph than the window it came out of is worse
 * than one carrying none, because it reads as someone else's document.
 *
 * The paths are authored in a 24x24 SVG viewport, y-down, which is exactly what pdf-lib's
 * `drawSvgPath` expects — it flips the axis itself.
 */
const MI_MARK_PATHS = [
  "M 6.6 11.85 Q 12 11.6 17.4 11.75 L 17.35 12.55 Q 12 12.35 6.65 12.65 Z",
  "M 11.55 6.6 L 12.45 6.55 Q 12.25 12.5 12.05 17.6 Q 11.95 17.85 11.85 17.6 Q 11.7 12.5 11.55 6.6 Z",
  "M 14.99 10.29 A 0.62 0.62 0 1 1 14.20 9.35 Q 15.97 8.11 17.90 7.05 Q 16.52 8.76 14.99 10.29 Z",
  "M 9.79 9.39 A 0.58 0.58 0 1 1 9.05 10.27 Q 7.56 8.52 5.95 6.92 Q 7.80 8.23 9.79 9.39 Z",
  "M 13.78 14.95 A 0.65 0.65 0 1 1 14.74 14.08 Q 16.26 16.10 17.62 18.24 Q 15.63 16.66 13.78 14.95 Z",
  "M 9.30 14.11 A 0.60 0.60 0 1 1 10.19 14.91 Q 8.26 16.42 6.51 18.09 Q 8.00 16.18 9.30 14.11 Z",
];

/**
 * The ink inside the 24x24 viewport, measured off the paths above.
 *
 * The glyph deliberately does not fill its box, so scaling by the box would leave the mark
 * looking undersized next to the label and sitting on a different optical centre. These
 * bounds let the footer be laid out around what is actually drawn. Re-measure them if the
 * paths ever change.
 */
const GLYPH = { minX: 5.95, maxX: 17.9, minY: 6.55, maxY: 18.24 };
const GLYPH_WIDTH = GLYPH.maxX - GLYPH.minX;
const GLYPH_CENTER_Y = (GLYPH.minY + GLYPH.maxY) / 2;

/**
 * Written into the document's Keywords so a second pass can recognize its own work.
 *
 * Publishing is retryable and a source PDF can be revised and re-staged, so "stamp it
 * again" has to be safe. Without this marker a file that went around the loop twice would
 * wear two marks, slightly offset, which looks like a rendering bug rather than a brand.
 */
export const MI_PDF_MARKER = "mi-generated-pdf";

/** The drawn width of the mark itself, not of its viewport. */
const MARK_SIZE = 7.5;
const LABEL_SIZE = 7;
/** Roughly the optical centre of Helvetica at this size, above the baseline. */
const LABEL_CENTER = LABEL_SIZE * 0.36;
const GAP = 3.5;
const MARGIN_RIGHT = 24;
const MARGIN_BOTTOM = 16;
/** Below this a sheet is a label or a stub, and a footer would land on top of the content. */
const MIN_STAMPABLE_EDGE = 144;

export interface PdfBrandingResult {
  bytes: Buffer;
  /** False whenever the bytes came back unchanged, for any reason. */
  applied: boolean;
  /** Empty when `applied` is true; otherwise the exact reason, for the human to read. */
  reason: string;
  pagesStamped: number;
  alreadyBranded?: boolean;
  pagesSkipped?: number;
}

/**
 * Maps a point given in the page's *displayed* orientation into unrotated page space.
 *
 * A /Rotate 90 sheet — routine for a plan set — is stored landscape and displayed
 * portrait. Stamping at the raw MediaBox bottom-right puts the mark up the side of the
 * printed sheet, so the anchor is expressed the way a person sees the page and converted
 * here, and the drawn content is turned by the same angle so it reads level.
 */
function toPageSpace(
  u: number,
  v: number,
  boxWidth: number,
  boxHeight: number,
  rotation: number,
): { x: number; y: number } {
  if (rotation === 90) return { x: boxWidth - v, y: u };
  if (rotation === 180) return { x: boxWidth - u, y: boxHeight - v };
  if (rotation === 270) return { x: v, y: boxHeight - u };
  return { x: u, y: v };
}

function normalizeRotation(angle: number): 0 | 90 | 180 | 270 {
  const normalized = ((Math.round(angle / 90) * 90) % 360 + 360) % 360;
  return normalized as 0 | 90 | 180 | 270;
}

/**
 * Stamps the Mi mark and "Generated by Mi" onto every page of an existing PDF.
 *
 * This never rasterizes: the original page content is untouched and the footer is added as
 * vector paths and a standard font, so text stays selectable and a drawing stays sharp.
 *
 * It is deliberately total rather than fussy — a PDF Mi cannot open (encrypted, malformed)
 * comes back unstamped with the reason attached instead of throwing, because refusing to
 * publish an approved document over a decorative footer is the worse failure. Callers must
 * report `applied: false` rather than quietly claiming the mark is there.
 */
export async function brandPdfWithMi(
  source: Buffer | Uint8Array,
  options: { label?: string } = {},
): Promise<PdfBrandingResult> {
  const original = Buffer.from(source);
  const label = (options.label ?? "Generated by Mi").slice(0, 120);
  let document: PDFDocument;
  try {
    document = await PDFDocument.load(original, { updateMetadata: false });
  } catch (cause) {
    return {
      bytes: original,
      applied: false,
      reason: `Mi could not open this PDF to stamp it: ${cause instanceof Error ? cause.message : String(cause)}`,
      pagesStamped: 0,
    };
  }

  const existingKeywords = document.getKeywords() ?? "";
  if (existingKeywords.includes(MI_PDF_MARKER)) {
    return { bytes: original, applied: false, alreadyBranded: true, reason: "This PDF already carries the Mi mark.", pagesStamped: 0 };
  }

  try {
    const font = await document.embedFont(StandardFonts.Helvetica);
    const ink = rgb(0.42, 0.45, 0.5);
    const labelWidth = font.widthOfTextAtSize(label, LABEL_SIZE);
    const blockWidth = MARK_SIZE + GAP + labelWidth;
    const markScale = MARK_SIZE / GLYPH_WIDTH;
    let pagesStamped = 0;

    for (const page of document.getPages()) {
      // Viewers and printers use the visible intersection, which may have a nonzero origin.
      const media = page.getMediaBox();
      const crop = page.getCropBox();
      const originX = Math.max(media.x, crop.x);
      const originY = Math.max(media.y, crop.y);
      const boxWidth = Math.min(media.x + media.width, crop.x + crop.width) - originX;
      const boxHeight = Math.min(media.y + media.height, crop.y + crop.height) - originY;
      const rotation = normalizeRotation(page.getRotation().angle);
      const displayedWidth = rotation === 90 || rotation === 270 ? boxHeight : boxWidth;
      const displayedHeight = rotation === 90 || rotation === 270 ? boxWidth : boxHeight;
      if (displayedWidth < MIN_STAMPABLE_EDGE || displayedHeight < MIN_STAMPABLE_EDGE) continue;
      if (blockWidth + MARGIN_RIGHT * 2 > displayedWidth) continue;

      // Anchor in displayed space: the left edge of the block, on the text baseline.
      const anchorU = displayedWidth - MARGIN_RIGHT - blockWidth;
      const anchorV = MARGIN_BOTTOM;
      // `drawSvgPath` anchors the viewport, not the ink: its origin is the top-left corner
      // of the 24x24 box, with y running down. Backing the glyph's own bounds out of that
      // is what puts the mark's left edge on the anchor and its middle on the label's
      // optical centre, instead of leaving it floating high and inset by its own padding.
      const markAnchor = toPageSpace(
        anchorU - GLYPH.minX * markScale,
        anchorV + LABEL_CENTER + GLYPH_CENTER_Y * markScale,
        boxWidth,
        boxHeight,
        rotation,
      );
      const textAnchor = toPageSpace(anchorU + MARK_SIZE + GAP, anchorV, boxWidth, boxHeight, rotation);
      // Turning the drawn content by the page's own rotation cancels the viewer's rotation,
      // so the footer reads level on the sheet as printed.
      const turn = degrees(rotation);

      for (const path of MI_MARK_PATHS) {
        page.drawSvgPath(path, {
          x: originX + markAnchor.x,
          y: originY + markAnchor.y,
          scale: markScale,
          rotate: turn,
          color: ink,
          borderWidth: 0,
        });
      }
      page.drawText(label, {
        x: originX + textAnchor.x,
        y: originY + textAnchor.y,
        size: LABEL_SIZE,
        font,
        color: ink,
        rotate: turn,
      });
      pagesStamped += 1;
    }

    const pagesSkipped = document.getPageCount() - pagesStamped;
    if (pagesStamped === 0) {
      return { bytes: original, applied: false, reason: "Every page was too small for a visible Mi footer.", pagesStamped: 0, pagesSkipped };
    }
    document.setProducer("Mi");
    document.setCreator("Mi");
    document.setModificationDate(new Date());
    // Only mark complete documents as branded: a skipped page must remain retryable.
    if (pagesSkipped === 0) document.setKeywords([existingKeywords, MI_PDF_MARKER].filter(Boolean));
    const stamped = Buffer.from(await document.save({ useObjectStreams: false }));
    return { bytes: stamped, applied: true, reason: pagesSkipped ? `${pagesSkipped} page(s) were too small for a visible Mi footer.` : "", pagesStamped, pagesSkipped };
  } catch (cause) {
    return {
      bytes: original,
      applied: false,
      reason: `Mi could not stamp this PDF: ${cause instanceof Error ? cause.message : String(cause)}`,
      pagesStamped: 0,
    };
  }
}
