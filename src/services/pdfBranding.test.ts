import { describe, expect, it } from "vitest";
import { PDFDocument, degrees } from "pdf-lib";
import { brandPdfWithMi, MI_PDF_MARKER } from "./pdfBranding";

describe("visible Mi PDF mark", () => {
  it.each([0, 90, 180, 270])("stays inside a cropped page rotated %i degrees", async (rotation) => {
    const pdf = await PDFDocument.create();
    const page = pdf.addPage([800, 1000]);
    page.setCropBox(100, 200, 500, 600);
    page.setRotation(degrees(rotation));
    const result = await brandPdfWithMi(await pdf.save());
    expect(result.applied).toBe(true);
    const { getDocument, Util } = await import("pdfjs-dist/legacy/build/pdf.mjs");
    const loading = getDocument({ data: new Uint8Array(result.bytes), useSystemFonts: true });
    try {
      const document = await loading.promise;
      const renderedPage = await document.getPage(1);
      const viewport = renderedPage.getViewport({ scale: 1 });
      const text = await renderedPage.getTextContent();
      const label = text.items.find((item) => "str" in item && item.str === "Generated by Mi");
      expect(label).toBeDefined();
      if (!label || !("transform" in label)) throw new Error("Missing footer");
      const display = Util.transform(viewport.transform, label.transform);
      expect(display[4]).toBeGreaterThan(viewport.width / 2);
      expect(display[4]).toBeLessThan(viewport.width - 24);
      expect(display[5]).toBeCloseTo(viewport.height - 16, 1);
    } finally { await loading.destroy(); }
  });

  it("does not claim tiny pages already carry a mark on a subsequent pass", async () => {
    const pdf = await PDFDocument.create();
    pdf.addPage([40, 40]);
    const source = await pdf.save();
    const first = await brandPdfWithMi(source);
    expect(first.applied).toBe(false);
    expect(first.bytes).toEqual(Buffer.from(source));
    expect((await PDFDocument.load(first.bytes)).getKeywords() ?? "").not.toContain(MI_PDF_MARKER);
    expect((await brandPdfWithMi(first.bytes)).alreadyBranded).not.toBe(true);
  });
});
